"""font_en.py: the English font cells the translation adds to the game's 1 bpp font.

The game already holds A-Z a-z 0-9 as 8x16 half-width cells (codes 01-1A, 1B-34, 36-3F, verified against the
drawn VRAM strip) plus ? ! : / = + % ~ as F0-prefixed half-width cells, so English needs no new letter art.
Punctuation that has no half-width glyph yet (period, comma, quotes, brackets, parens, ...) is drawn here into
blank 8x16 cells that the script never uses: 0x114-0x12B (two-byte codes F0 14 .. F0 2B).

Cell format: 16 rows of 8 characters, '#' = ink. Bit order in the cell is the renderer's nibble order
(bits 6,7,4,5,2,3,0,1 = x 0..7), so `glyph_bytes` converts.

    python -X utf8 tools/font_en.py check          # metrics + overlap self-test
    python -X utf8 tools/font_en.py sheet OUT.png  # render the cells to look at them
"""
