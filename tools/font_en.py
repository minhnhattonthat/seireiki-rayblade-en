LATIN = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789")
EXISTING = {" ": 0x00, "?": 0x108, "!": 0x109, ":": 0x10A, "/": 0x103, "=": 0x104,
            "+": 0x105, "%": 0x100, "~": 0x101}


def cell(ch):
    """16 rows x 8 columns of 0/1 for a character we add (KeyError for ones the font already has)."""
    rows = [r for r in ART[ch].strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 8 for r in rows), (ch, len(rows))
    return [[1 if c == "#" else 0 for c in r] for r in rows]


def glyph_bytes(ch):
    """16 bytes, one per row, in the renderer's bit order."""
    out = bytearray()
    for row in cell(ch):
        b = 0
        for x, v in enumerate(row):
            if v:
                b |= 1 << ORDER[x]
        out.append(b)
    return bytes(out)


def patch(exe, put):
    """Write every added cell into the EXE font (base file offset 0xA03CC) through `put`."""
    base = 0xA03CC
    for code, ch in sorted(GLYPHS.items()):
        put(exe, base + code * 16, glyph_bytes(ch), f"font_en {ch!r} cell {code:03X}")
    return exe


CANARY = "The quick brown fox jumps over the lazy dog!?,.:;'\"-()[]&*<>#$@_`{}|\\^ 0123456789"


def check():
    used = set()
    for code, ch in GLYPHS.items():
        assert 0x114 <= code <= 0x12B, code
        assert ch not in used, f"{ch!r} twice"
        used.add(ch)
        b = glyph_bytes(ch)
        ink = sum(bin(x).count("1") for x in b)
        top = next((r for r in range(16) if b[r]), 16)
        bot = next((r for r in range(15, -1, -1) if b[r]), -1)
        assert ink, ch
        assert bot <= 15 and top >= 2, (ch, top, bot)
    missing = [c for c in CANARY if c not in GLYPHS.values() and c not in EXISTING and c not in LATIN]
    assert not missing, f"no glyph for {missing!r}"
    print(f"font_en ok: {len(GLYPHS)} added cells, every printable ASCII has a glyph")


def sheet(out):
    from PIL import Image, ImageDraw
    zoom = 6
    cols = 8
    cells = sorted(GLYPHS.items())
    rows = (len(cells) + cols - 1) // cols
    im = Image.new("L", (cols * (8 * zoom + 10), rows * (16 * zoom + 16)), 255)
    d = ImageDraw.Draw(im)
    for i, (code, ch) in enumerate(cells):
        x0, y0 = (i % cols) * (8 * zoom + 10), (i // cols) * (16 * zoom + 16)
        d.text((x0, y0), f"{ch} {code:03X}", fill=128)
        for y, row in enumerate(cell(ch)):
            for x, v in enumerate(row):
                if v:
                    d.rectangle([x0 + x * zoom, y0 + 12 + y * zoom, x0 + x * zoom + zoom - 1,
                                 y0 + 12 + y * zoom + zoom - 1], fill=0)
    im.save(out)
    print(out)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "check":
        check()
    elif cmd == "sheet":
        sheet(sys.argv[2])
