"""build_tbl.py: write tbl/jp.tbl from the hand-read low codes, work/font/match.tsv (template guesses) and
tbl/glyph_overrides.tsv (reviewed readings, win over guesses).

Byte form of glyph code c: c < 0xF0 -> one byte c; c >= 0x100 -> two bytes (0xEF + (c >> 8), c & 0xFF).
Duplicate readings get a `#<code>` suffix (e.g. `亜#3A1`) so decode -> encode stays byte-exact; review clears them.

    python -X utf8 tools/build_tbl.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

HIRA = [chr(c) for c in range(ord("ぁ"), ord("ん") + 1) if chr(c) not in "ゎゐゑ"]
KATA = [chr(c) for c in range(ord("ァ"), ord("ン") + 1) if chr(c) not in "ヮヰヱ"]

LOW = {0x00: "　"}
LOW.update({0x01 + i: chr(ord("A") + i) for i in range(26)})
LOW.update({0x1B + i: chr(ord("a") + i) for i in range(26)})
LOW.update({0x36 + i: str(i) for i in range(10)})
LOW.update({0x40 + i: c for i, c in enumerate(HIRA)})
LOW.update({0x90 + i: c for i, c in enumerate(KATA)})
LOW.update({0xE0: "ヴ", 0xE1: "<E1>", 0xE2: "ヵ", 0xE3: "ヱ", 0xE4: "々", 0xE5: "、", 0xE6: "。", 0xE7: "．",
            0xE8: "（", 0xE9: "）", 0xEA: "「", 0xEB: "」", 0xEC: "『", 0xED: "』", 0xEE: "・"})
LOW.update({0x100: "％", 0x101: "～", 0x102: "♥", 0x103: "／", 0x104: "＝", 0x105: "＋", 0x106: "ー", 0x107: "±",
            0x108: "？", 0x109: "！", 0x10A: "：", 0x10B: "‥", 0x10C: "→", 0x10D: "←", 0x110: "─",
            0x111: "<111>", 0x112: "<112>", 0x113: "<113>"})
LOW.update({0x201: "㎜", 0x202: "㎞", 0x203: "∞", 0x204: "＜", 0x205: "＞", 0x206: "“", 0x207: "”", 0x208: "○",
            0x209: "×", 0x20A: "△", 0x20B: "□", 0x20C: "‼", 0x20D: "⁉", 0x20E: "⁈"})

CONTROLS = [  # verified status: see docs/re/text.md
    "FB={fb}",
    "FC={ctl:2}",
    "FD={nl}",
    "FE={page}",
    "FF={end}",
]


def code_bytes(c):
    return bytes([c]) if c < 0xF0 else bytes([0xEF + (c >> 8), c & 0xFF])


def main():
    reading = dict(LOW)
    for line in (ROOT / "work/font/match.tsv").read_text(encoding="utf-8").splitlines()[1:]:
        f = line.split("\t")
        c = int(f[0], 16)
        if c >= 0x210 and f[1]:
            reading[c] = f[1]
    ov = ROOT / "tbl/glyph_overrides.tsv"
    if ov.exists():
        for line in ov.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                k, v = line.split("\t")[:2]
                reading[int(k, 16)] = v
    seen, out = {}, ["# Seireiki Rayblade (PS1) dialogue font table. Generated by tools/build_tbl.py; edit the sources."]
    for c in sorted(reading):
        v = reading[c]
        if v in seen:
            v = f"{v}#{c:03X}"
        seen.setdefault(reading[c], c)
        out.append(f"{code_bytes(c).hex().upper()}={v}")
    out += CONTROLS
    (ROOT / "tbl").mkdir(exist_ok=True)
    (ROOT / "tbl/jp.tbl").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("tbl/jp.tbl", len(out) - 1, "entries")


if __name__ == "__main__":
    main()
